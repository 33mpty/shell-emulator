"""Разбор строки, введённой пользователем, на команду и аргументы."""


def parse_line(line):
    """Разделить строку по пробелам.

    Возвращает пару (команда, список аргументов).
    Если строка пустая, команда будет None.
    """
    parts = line.split()
    if not parts:
        return None, []
    return parts[0], parts[1:]
